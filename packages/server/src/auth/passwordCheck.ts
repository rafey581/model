import bcrypt from 'bcryptjs'

/**
 * A real bcrypt hash of a value nobody knows, compared when the account does not
 * exist or the stored hash is not bcrypt. Without it, "no such user" returns
 * immediately while a wrong password takes a full bcrypt round.
 */
const DUMMY_HASH = '$2b$10$C6UzMDM.H6dfI/f/IKcEe.iaWs1JOwuijCzFvJcF1aF8b5K2PnO7TC'

/** True only when `hash` is a bcrypt hash and it matches. Always does one compare. */
export function passwordMatches(password: string, hash: string | null | undefined): boolean {
  const stored = hash && hash.startsWith('$2') ? hash : DUMMY_HASH
  try {
    const ok = bcrypt.compareSync(password, stored)
    return Boolean(hash && hash.startsWith('$2') && ok)
  } catch {
    try {
      bcrypt.compareSync(password, DUMMY_HASH)
    } catch {
      // The dummy hash is a constant generated by bcrypt. A failure here still
      // must not become a successful login.
    }
    return false
  }
}
